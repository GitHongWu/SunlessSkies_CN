using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using System.Text.RegularExpressions;
using HarmonyLib;

namespace SunlessSkiesCN.Shared
{
    // Translate the displayed result only, never the backing quality or inventory.
    public static class ItemTooltipLocalization
    {
        public const string WeightTemplate = "Weight: {value1}";
        static readonly Regex Weight = new Regex(@"(?<prefix>\A|[\r\n])Weight: (?<number>[0-9]+)(?=\r|\n|\z)", RegexOptions.CultureInvariant);
        static readonly Regex Markup = new Regex(@"<[^>]*>|\[[^\]]*\]|\{[^{}]*\}", RegexOptions.CultureInvariant);
        static readonly Regex Pieces = new Regex(@"(<[^>]*>|\r\n|\r|\n)");
        static readonly Regex Stat = new Regex(@"\A(?<label>Damage: |Blast Damage: |Range: |Heat: |Tier )(?<n>[+-]?[0-9]+(?:[.,][0-9]+)?)\z");
        static readonly Regex Effect = new Regex(@"\A(?<n>[+-]?[0-9]+) (?<name>[^<>\r\n]+)\z");
        static readonly Regex Requirement = new Regex(@"\A(?<name>[^<>\r\n]+) at (?<n>[0-9]+)\+\z");
        static readonly string[] Labels = { "Effects:", "Requires:", "With sufficient crew:", "Movement Speed:", "Fuel Consumption:", "Full Steam Speed:" };
        static readonly Dictionary<MethodBase, PropertyInfo> descriptions = new Dictionary<MethodBase, PropertyInfo>();
        static Func<string, string> lookup;
        static Func<bool> enabled;
        static Action<string> log;
        static int traces;

        public static void Install(Assembly game, Func<string,string> translate, Func<bool> active, Action<string> logger)
        {
            var helper = game.GetType("Skyless.Assets.Code.Skyless.UI.FormatHelpers.TooltipHelper", true);
            var methods = new List<MethodInfo>();
            foreach (string name in new[] { "Failbetter.Core.Quality", "Failbetter.Presentation.PresentationData.PossessionPresentation" })
            {
                var type = game.GetType(name, true);
                var method = AccessTools.Method(helper, "GetTooltipDescription", new[] { type });
                var property = type.GetProperty("Description");
                if (method == null || method.ReturnType != typeof(string) || property == null || property.PropertyType != typeof(string) || !property.CanRead)
                    throw new MissingMethodException("Unsupported item tooltip API: " + name);
                descriptions[method] = property;
                methods.Add(method);
            }
            lookup = translate; enabled = active; log = logger;
            var harmony = new Harmony("githongwu.sunlessskies.item-tooltip");
            try { foreach (var method in methods) harmony.Patch(method, postfix: new HarmonyMethod(typeof(ItemTooltipLocalization), "Postfix")); }
            catch { harmony.UnpatchSelf(); throw; }
            log("Item tooltip localization ready: both TooltipHelper.GetTooltipDescription overloads.");
        }

        static void Postfix(object __0, MethodBase __originalMethod, ref string __result)
        {
            try
            {
                if (!enabled() || __0 == null) return;
                var description = descriptions[__originalMethod].GetValue(__0, null) as string;
                string translated = Localize(__result, description, lookup);
                if (translated != __result && traces++ < 4) log("Item tooltip localized.");
                __result = translated;
            }
            catch (Exception e) { if (traces++ < 4) log("Item tooltip fallback: " + e.Message); }
        }

        public static string Localize(string text, string description, Func<string,string> translate)
        {
            if (String.IsNullOrEmpty(text)) return text;
            string body = "", suffix = text;
            if (!String.IsNullOrEmpty(description))
            {
                // Require the exact description prefix generated by the helper.
                // Do not infer paragraph boundaries from arbitrary rich text.
                if (!text.StartsWith(description, StringComparison.Ordinal)) return text;
                body = TranslateDescription(description, translate);
                suffix = text.Substring(description.Length);
            }
            string template = translate(WeightTemplate);
            if (!String.IsNullOrEmpty(template) && template != WeightTemplate &&
                template.Split(new[] { "{value1}" }, StringSplitOptions.None).Length == 2 &&
                template.Replace("{value1}", "").IndexOfAny(new[] { '{', '}', '<', '>', '[', ']', '\r', '\n' }) < 0)
                suffix = Weight.Replace(suffix, m => m.Groups["prefix"].Value + template.Replace("{value1}", m.Groups["number"].Value));
            return body + LocalizeEquipmentSuffix(suffix, translate);
        }

        public static string LocalizeEquipmentSuffix(string suffix, Func<string,string> translate)
        {
            // Only called for the helper's appended fields, never the item prose.
            return String.Concat(Pieces.Split(suffix).Select(piece =>
            {
                string core = piece.Trim();
                if (core.Length == 0 || core.StartsWith("<", StringComparison.Ordinal)) return piece;
                string result = core;
                var stat = Stat.Match(core);
                var requirement = Requirement.Match(core);
                var effect = Effect.Match(core);
                if (Labels.Contains(core)) result = Plain(core, translate);
                else if (stat.Success) result = Render(stat.Groups["label"].Value + "{value1}", new[] { stat.Groups["n"].Value }, core, translate);
                else if (requirement.Success) result = Render("{value1} at {value2}+", new[] { Plain(requirement.Groups["name"].Value, translate), requirement.Groups["n"].Value }, core, translate);
                else if (effect.Success) result = effect.Groups["n"].Value + " " + Plain(effect.Groups["name"].Value, translate);
                int start = piece.IndexOf(core, StringComparison.Ordinal);
                return piece.Substring(0, start) + result + piece.Substring(start + core.Length);
            }).ToArray());
        }

        static string Plain(string source, Func<string,string> translate)
        {
            string value = translate(source);
            return String.IsNullOrWhiteSpace(value) || value.IndexOfAny(new[] { '<', '>', '[', ']', '{', '}', '\r', '\n' }) >= 0 ? source : value;
        }

        static string Render(string template, string[] values, string fallback, Func<string,string> translate)
        {
            string result = translate(template);
            if (String.IsNullOrWhiteSpace(result) || result == template || result.IndexOfAny(new[] { '<', '>', '[', ']', '\r', '\n' }) >= 0) return fallback;
            string rest = result;
            for (int i = 0; i < values.Length; i++)
            {
                string slot = "{value" + (i + 1) + "}";
                if (rest.Split(new[] { slot }, StringSplitOptions.None).Length != 2) return fallback;
                rest = rest.Replace(slot, "");
            }
            if (rest.IndexOfAny(new[] { '{', '}' }) >= 0) return fallback;
            return Regex.Replace(result, @"\{value([0-9]+)\}", m => values[Int32.Parse(m.Groups[1].Value) - 1]);
        }

        static string TranslateDescription(string source, Func<string,string> translate)
        {
            string core = source.Trim();
            if (core.Length == 0) return source;
            // Prefer exact input. A terminal newline alias handles differences
            // between Steam descriptions and the selected ParaTranz source.
            foreach (string candidate in new[] { source, core, core + "\n", core + "\r\n" }.Distinct())
            {
                string result = translate(candidate);
                if (String.IsNullOrWhiteSpace(result) || result == candidate) continue;
                if (!Markup.Matches(source).Cast<Match>().Select(m => m.Value)
                    .SequenceEqual(Markup.Matches(result).Cast<Match>().Select(m => m.Value))) continue;
                int start = source.IndexOf(core, StringComparison.Ordinal);
                return source.Substring(0, start) + result.Trim() + source.Substring(start + core.Length);
            }
            return source;
        }
    }
}
